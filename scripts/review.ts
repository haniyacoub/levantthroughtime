/**
 * npm run review
 *
 * Writes data/REVIEW.md: a checklist for human reviewers.
 *   1. Source balance: which kinds of sources (academic, government, UN…) and which
 *      institutional countries each era relies on, so one-sided topics stand out.
 *   2. Every contested item, with its sources.
 *   3. Weakly sourced items: only checked at catalogue level, only seen second-hand,
 *      or "documented" on a single source.
 *   4. Translations still marked machine-draft.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DATA } from './lib/io';
import { validateData } from './lib/validate';
import { startT } from '../src/time/years';

const { bundle: b, warnings } = validateData(DATA);
const sources = new Map((b.sources?.sources ?? []).map((s) => [s.id, s]));
const eras = (b.eras?.segments ?? []).map((e) => ({ id: e.id, label: e.label.en, t0: startT(e.start) }));
const eraOf = (t: number) => [...eras].reverse().find((e) => t >= e.t0 - 1e-9)?.label ?? eras[0]?.label ?? '?';

interface Rec {
  file: string;
  id: string;
  label: string;
  t: number | null;
  confidence?: string;
  refs: { ref: string; via?: string }[];
}
const recs: Rec[] = [];
const push = (file: string, id: string, label: string, date: { year: number; month?: number } | undefined, confidence: string | undefined, refs: { ref: string; via?: string }[] | undefined) =>
  recs.push({ file, id, label, t: date ? startT(date) : null, confidence, refs: refs ?? [] });

for (const p of b.polities?.polities ?? []) {
  push('polities.json', p.id, p.name.en, p.start, p.confidence, p.sources);
  for (const [i, r] of (p.relations ?? []).entries()) push('polities.json', `${p.id} › relations[${i}]`, `${p.name.en} → ${r.type} of ${r.overlord}`, r.start, r.confidence, r.sources);
}
for (const c of b.cultures?.cultures ?? []) push('cultures.json', c.id, c.name.en, c.start, c.confidence, c.sources);
for (const { file, data } of b.territories) for (const f of data.features) push(file, f.properties.id, `territory of ${f.properties.polity}`, f.properties.start, f.properties.confidence, f.properties.sources);
for (const p of b.population?.population ?? []) push('population.json', p.id, `population ${p.area}`, p.date, p.confidence, p.sources);
for (const p of b.places?.places ?? []) push('places.json', p.id, p.name.en, undefined, p.confidence, p.sources);
for (const e of b.events?.events ?? []) push('events.json', e.id, e.name.en, e.date, e.confidence, e.sources);
for (const r of b.rulers?.rulers ?? []) push('rulers.json', r.id, r.name.en, r.start, r.confidence, r.sources);
for (const c of b.conflicts?.conflicts ?? []) push('conflicts.json', c.id, c.name.en, c.start, c.confidence, c.sources);
for (const m of b.migrations?.migrations ?? []) push('migrations.json', m.id, m.name.en, m.start, m.confidence, m.sources);
for (const p of b.perspectives?.perspectives ?? []) for (const a of p.accounts) push('perspectives.json', `${p.id} › ${a.perspective}`, p.title.en, undefined, 'contested', a.sources);

const lines: string[] = [];
const out = (s = '') => lines.push(s);
const today = new Date().toISOString().slice(0, 10);

out('# Review checklist');
out();
out(`Generated by \`npm run review\` on ${today}. Do not edit by hand; edit the data and run it again. Decisions taken when importing data are recorded in [CHANGELOG.md](CHANGELOG.md).`);
out();
out(`Totals: ${b.sources?.sources.length ?? 0} sources; ${recs.length} sourced records; ${warnings.length} validator warnings.`);
out();

// ---------------------------------------------------------------- 1. balance
out('## 1. Source balance by era');
out();
out('How many citations in each era come from each kind of source and from institutions in each country. A topic that relies on one side only should get sources from the other side and from independent scholarship.');
out();
const byEra = new Map<string, { kinds: Map<string, number>; countries: Map<string, number>; n: number }>();
for (const r of recs) {
  if (r.t === null) continue;
  const era = eraOf(r.t);
  const e = byEra.get(era) ?? { kinds: new Map(), countries: new Map(), n: 0 };
  for (const ref of r.refs) {
    const s = sources.get(ref.ref);
    if (!s) continue;
    e.n++;
    e.kinds.set(s.kind, (e.kinds.get(s.kind) ?? 0) + 1);
    const c = s.institution_country ?? '?';
    e.countries.set(c, (e.countries.get(c) ?? 0) + 1);
  }
  byEra.set(era, e);
}
const top = (m: Map<string, number>, n: number) => [...m.entries()].sort((a, c) => c[1] - a[1]).slice(0, 6).map(([k, v]) => `${k} ${Math.round((100 * v) / n)}%`).join(', ');
out('| Era | Citations | By kind | By institutional country | Flag |');
out('|---|---|---|---|---|');
for (const e of eras) {
  const d = byEra.get(e.label);
  if (!d || !d.n) continue;
  const il = d.countries.get('IL') ?? 0;
  const ps = d.countries.get('PS') ?? 0;
  const flag = e.t0 >= 1900 && (il > 3 * Math.max(1, ps) || ps > 3 * Math.max(1, il)) ? `⚠ IL ${il} / PS ${ps}` : '';
  const ref = (d.kinds.get('reference') ?? 0) / d.n > 0.5 ? ' ⚠ mostly reference works' : '';
  out(`| ${e.label} | ${d.n} | ${top(d.kinds, d.n)} | ${top(d.countries, d.n)} | ${flag}${ref} |`);
}
out();

// ---------------------------------------------------------------- 2. contested
out('## 2. Contested items');
out();
out('Each needs a reviewer to check that the competing positions are fairly stated and sourced.');
out();
const contested = recs.filter((r) => r.confidence === 'contested' && r.file !== 'perspectives.json');
for (const file of [...new Set(contested.map((r) => r.file))]) {
  out(`### ${file}`);
  for (const r of contested.filter((x) => x.file === file)) out(`- \`${r.id}\` — ${r.label} (sources: ${[...new Set(r.refs.map((x) => x.ref))].join(', ')})`);
  out();
}

// ---------------------------------------------------------------- 3. weak
out('## 3. Weakly sourced items');
out();
out('Records whose every source was only confirmed at catalogue level, or only seen quoted in another work. Someone with library access should check the original and update the verification level.');
out();
const weak = recs.filter(
  (r) => r.refs.length > 0 && r.refs.every((x) => ['catalogue-only', 'cited-via'].includes(sources.get(x.ref)?.verification.level ?? '')),
);
for (const r of weak) out(`- ${r.file} › \`${r.id}\` — ${r.label} (${[...new Set(r.refs.map((x) => `${x.ref} [${sources.get(x.ref)?.verification.level}]`))].join(', ')})`);
out();
out('### Validator warnings');
out();
for (const w of warnings) out(`- data/${w.file} › ${w.where}: ${w.message}`);
out();

// ---------------------------------------------------------------- 4. translations
out('## 4. Translations awaiting review');
out();
let drafts = 0;
let reviewed = 0;
const walk = (o: unknown): void => {
  if (Array.isArray(o)) o.forEach(walk);
  else if (o && typeof o === 'object') {
    const rec = o as Record<string, unknown>;
    const st = rec.translation_status as Record<string, string> | undefined;
    if (st && typeof rec.en === 'string') {
      for (const v of Object.values(st)) {
        if (v === 'machine-draft') drafts++;
        if (v === 'reviewed') reviewed++;
      }
    }
    Object.values(rec).forEach(walk);
  }
};
walk([b.polities, b.cultures, b.eras, b.places, b.events, b.rulers, b.conflicts, b.migrations, b.languages, b.perspectives, b.stories.map((s) => s.data), b.config, b.areas, b.groups]);
out(`${drafts} Arabic/Hebrew texts are machine drafts; ${reviewed} have been reviewed. Interface strings in src/i18n/locales/ar.json and he.json are also machine drafts.`);
out();

writeFileSync(join(DATA, 'REVIEW.md'), lines.join('\n') + '\n');
console.log(`✓ data/REVIEW.md: ${contested.length} contested, ${weak.length} weakly sourced, ${warnings.length} warnings, ${drafts} draft translations`);
